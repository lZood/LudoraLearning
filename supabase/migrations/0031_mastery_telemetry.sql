-- 0031_mastery_telemetry — DOMINIO POR CONCEPTO + TELEMETRÍA append-only
-- (Master Plan §3.2 fila 0031, §3.4 motor, §3.5 un solo camino de escritura).
--
-- Cierra el loop de aprendizaje: cada intento YA VALIDADO mueve el theta del
-- concepto con el MISMO Elo unitario probado en src/lib/diagnostic.ts (eloStep),
-- programa repaso espaciado (HLR) y hace rollup a user_skills.mastery (columna
-- huérfana de 0007). Toda escritura pasa por RPC SECURITY DEFINER service_role-only
-- (patrón 0023); el cliente nunca decide dominio ni XP.
--
-- ADITIVO y RETROCOMPATIBLE: tablas/RPC nuevas con IF NOT EXISTS / OR REPLACE;
-- nada del esquema actual cambia. DEGRADACIÓN ELEGANTE: con user_concept_mastery
-- vacío, apply_lesson_attempts solo escribe telemetría y devuelve 0 cruces => el
-- orquestador paga solo XP de Esfuerzo (no-op de dominio).
--
-- Resolución de conceptos: el JSONB de contenido referencia por SLUG estable; las
-- RPC aceptan slug O uuid y resuelven contra concepts (0028).
-- =============================================================================

-- ── 0) Helpers puros (IMMUTABLE) compartidos por las RPC ─────────────────────
-- Banda de dominio derivada de theta vs dificultad del concepto (CEFR 1–6).
-- Espeja la noción de "Encantamiento" del plan: aprendiendo < competente < dominado.
CREATE OR REPLACE FUNCTION public._mc_mastery_band(p_theta REAL, p_difficulty REAL)
RETURNS TEXT LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE
    WHEN p_theta >= COALESCE(p_difficulty, 3.0) + 0.5 THEN 'dominado'
    WHEN p_theta >= COALESCE(p_difficulty, 3.0) - 0.5 THEN 'competente'
    ELSE 'aprendiendo' END;
$$;

-- % de dominio para UI/rollup: masteryPct = round(clamp((theta-1)/5,0,1)*100).
CREATE OR REPLACE FUNCTION public._mc_mastery_pct(p_theta REAL)
RETURNS INT LANGUAGE sql IMMUTABLE AS $$
  SELECT GREATEST(0, LEAST(100, round(((p_theta - 1) / 5.0) * 100)))::int;
$$;

-- Rango ordinal de banda (para detectar CRUCES hacia arriba = pago de Encantamiento).
CREATE OR REPLACE FUNCTION public._mc_band_rank(p_band TEXT)
RETURNS INT LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE p_band WHEN 'dominado' THEN 2 WHEN 'competente' THEN 1 ELSE 0 END;
$$;

